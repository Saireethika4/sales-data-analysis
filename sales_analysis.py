# Import libraries
import matplotlib.pyplot as plt

# -------------------------------
# Data for MAE Comparison (Bar Chart)
# -------------------------------
models = ['Linear Regression', 'ARIMA', 'Random Forest', 'LSTM', 'XGBoost']
mae_values = [0.82, 1.01, 0.65, 0.60, 0.52]

# -------------------------------
# Data for Accuracy Comparison (Line Chart)
# -------------------------------
algorithms = ['ARIMA', 'Linear Regression', 'SVM', 'Decision Tree', 'Random Forest', 'LSTM']
accuracy = [68, 72, 78, 75, 85, 88]

# -------------------------------
# Create Figure with 2 Plots
# -------------------------------
plt.figure(figsize=(14, 6))

# -------- Bar Chart --------
plt.subplot(1, 2, 1)
plt.bar(models, mae_values)
plt.title('MAE Comparison of Sales Forecasting Models')
plt.xlabel('Forecasting Models')
plt.ylabel('Mean Absolute Error (MAE)')
plt.xticks(rotation=30)

# -------- Line Chart --------
plt.subplot(1, 2, 2)
plt.plot(algorithms, accuracy, marker='o')
plt.title('Accuracy Comparison of Sales Forecasting Algorithms')
plt.xlabel('Forecasting Algorithms')
plt.ylabel('Accuracy (%)')
plt.xticks(rotation=30)

# Layout fix
plt.tight_layout()

# Show plots
plt.show()

