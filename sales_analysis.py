# Import libraries
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# -------------------------------
# Create Sample Data (like your image)
# -------------------------------
dates = pd.date_range(start='2025-02-01', end='2025-03-31', freq='7D')
status = ['Pending', 'Cancelled', 'Payment Completed', 'Product Sale']

# Generate heatmap values (order count)
np.random.seed(0)
data = np.random.randint(200, 1800, size=(len(status), len(dates)))

df = pd.DataFrame(data, index=status, columns=dates)

# -------------------------------
# Plot Heatmap
# -------------------------------
plt.figure(figsize=(12, 6))

sns.heatmap(df, cmap="YlOrRd", linewidths=0.5, linecolor='white', cbar_kws={'label': 'Order Count'})

# -------------------------------
# Add Trend Lines (overlay)
# -------------------------------
for i in range(len(status)):
    plt.plot(np.arange(len(dates)) + 0.5,
             [i + 0.5]*len(dates),
             marker='o', linewidth=1)

# -------------------------------
# Labels & Title
# -------------------------------
plt.title('Retail Sales & Order Status Trends (2025)')
plt.xlabel('Date (2025)')
plt.ylabel('Order Status')

# Format x-axis labels
plt.xticks(ticks=np.arange(len(dates)) + 0.5,
           labels=[d.strftime('%b %d') for d in dates],
           rotation=30)

plt.yticks(rotation=0)

plt.tight_layout()
plt.show()